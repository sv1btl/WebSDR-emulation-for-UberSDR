/** 'HHMM label' strings -> [{ sec, label }] sorted by time of day. */
export function parseSlots(list) {
  const out = [];
  for (const item of (list || [])) {
    const m = /^(\d{2})(\d{2})\s*(.*)$/.exec(item);
    if (!m) continue;
    out.push({ sec: (+m[1]) * 3600 + (+m[2]) * 60, label: m[3] });
  }
  return out.sort((a, b) => a.sec - b.sec);
}

/** Broadcast times of one NAVTEX station, in seconds UTC. */
export function navtexSlots(st) {
  if (Array.isArray(st.t)) return st.t.map(m => m * 60).sort((a, b) => a - b);
  const iv = (st.iv || 240) * 60;
  const t0 = (st.t0 !== undefined ? st.t0 * 60 : (st.id.toUpperCase().charCodeAt(0) - 65) * 600);
  const out = [];
  for (let t = t0 % 86400; out.length < Math.max(1, Math.round(86400 / iv)); t += iv) {
    out.push(t % 86400);
  }
  return out.sort((a, b) => a - b);
}

function hms(sec) {
  const h = Math.floor(sec / 3600), m = Math.floor((sec % 3600) / 60), s = sec % 60;
  const p2 = n => String(n).padStart(2, '0');
  return h > 0 ? `${h}h ${p2(m)}m` : `${p2(m)}m ${p2(s)}s`;
}

/**
 * Turn slots into display rows, keeping whatever is transmitting right now at
 * the top instead of pushing it 24 h into the future.
 *
 * @param slots  [{ sec, label, ...extra }]
 * @param nowSec seconds since 00:00 UTC
 * @param opts   { maxDur, minDur, limit }  maxDur/minDur clamp how long a slot
 *               is considered on air when the gap to the next one is unusual.
 */
export function scheduleRows(slots, nowSec, opts = {}) {
  if (!slots || !slots.length) return [];
  const maxDur = opts.maxDur !== undefined ? opts.maxDur : 12 * 60;
  const minDur = opts.minDur !== undefined ? opts.minDur : 60;
  const sorted = slots.slice().sort((a, b) => a.sec - b.sec);

  const rows = sorted.map((slot, i) => {
    const next = sorted[(i + 1) % sorted.length];
    let gap = next.sec - slot.sec;
    if (gap <= 0) gap += 86400;
    if (sorted.length === 1) gap = 86400;
    const dur = Math.max(minDur, Math.min(maxDur, gap));

    let since = nowSec - slot.sec;
    if (since < 0) since += 86400;               // slot was earlier today/yesterday
    const onAir = since < dur;
    let wait = slot.sec - nowSec;
    if (wait < 0) wait += 86400;

    const hh = Math.floor(slot.sec / 3600), mm = Math.floor((slot.sec % 3600) / 60);
    return {
      ...slot,
      utc: `${String(hh).padStart(2, '0')}:${String(mm).padStart(2, '0')}`,
      nextUTC: `${String(hh).padStart(2, '0')}:${String(mm).padStart(2, '0')}`,
      secUntil: onAir ? 0 : wait,
      onAir,
      elapsed: onAir ? since : 0,
      countdown: onAir ? 'ON AIR' : hms(wait),
      label2:    onAir ? 'ON AIR' : hms(wait),
      urgent:   !onAir && wait <= 180,
      imminent: !onAir && wait <= 30,
    };
  });

  rows.sort((a, b) =>
    (a.onAir === b.onAir) ? (a.onAir ? b.elapsed - a.elapsed : a.secUntil - b.secUntil)
                          : (a.onAir ? -1 : 1));
  return opts.limit ? rows.slice(0, opts.limit) : rows;
}
